// Turns your .env (or real environment variables, e.g. in CI) into js/env-config.js,
// the small file the browser app reads its Firebase and Supabase settings from.
//
//   node scripts/generate-config.mjs            -> js/env-config.js
//   node scripts/generate-config.mjs dist/js/env-config.js

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const KEYS = [
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'SUPABASE_BUCKET',
  'SUPABASE_USE_FIREBASE_JWT',
  'MAX_UPLOAD_MB',
];

const OPTIONAL = new Set([
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'SUPABASE_USE_FIREBASE_JWT',
  'MAX_UPLOAD_MB',
]);

const REQUIRED = KEYS.filter((k) => !OPTIONAL.has(k));

export const isPlaceholderValue = (v) =>
  !v || /^(?:https?:\/\/)?your[-_]/i.test(v) || /your-project/i.test(v);

export function parseEnv(text) {
  const out = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"') && value.length >= 2) ||
      (value.startsWith("'") && value.endsWith("'") && value.length >= 2)
    ) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, ''); // trailing comment
    }
    out[key] = value;
  }
  return out;
}

export function buildConfig({ envFile = resolve(root, '.env'), env = process.env } = {}) {
  const hasFile = existsSync(envFile);
  const fromFile = hasFile ? parseEnv(readFileSync(envFile, 'utf8')) : {};
  const values = {};
  for (const key of KEYS) {
    const v = env[key] ?? fromFile[key];
    if (v !== undefined && v !== '') values[key] = String(v);
  }
  const missing = REQUIRED.filter((k) => isPlaceholderValue(values[k]));
  return { values, missing, hasFile };
}

export function writeConfig(target = resolve(root, 'js/env-config.js'), options) {
  const { values, missing, hasFile } = buildConfig(options);
  mkdirSync(dirname(target), { recursive: true });
  const body =
    '// Generated by scripts/generate-config.mjs — do not edit, do not commit.\n' +
    `window.__YORIN_ENV__ = ${JSON.stringify(values, null, 2)};\n`;
  writeFileSync(target, body);
  return { target, missing, hasFile };
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const target = process.argv[2] ? resolve(process.argv[2]) : undefined;
  const { target: written, missing, hasFile } = writeConfig(target);
  console.log(`Wrote ${written}`);
  if (!hasFile) console.warn('! No .env file found. Copy .env.example to .env and fill it in (see FIREBASE_SETUP.md & SUPABASE_SETUP.md).');
  if (missing.length) {
    console.warn(`! Missing or placeholder values: ${missing.join(', ')}`);
    console.warn('  The app will show a setup screen until these are set.');
  }
}
